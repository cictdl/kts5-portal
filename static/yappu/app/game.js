  function score(guess, target) {
    var n = target.length, res = new Array(n), left = {};
    for (var i = 0; i < n; i++) {
      if (guess[i] === target[i]) res[i] = 'hit';
      else left[target[i]] = (left[target[i]] || 0) + 1;
    }
    for (var j = 0; j < n; j++) {
      if (res[j]) continue;
      if (left[guess[j]]) { res[j] = 'near'; left[guess[j]]--; }
      else if (consOf(guess[j]) && consOf(guess[j]) === consOf(target[j])) res[j] = 'kin';
      else res[j] = 'miss';
    }
    return res;
  }

